-- 回写统计（confirm_order 走的是增量 +1，这里用全量重算，两者结果一致但种子更适合重算）
update dishes d
   set eat_count = s.n, last_eaten_at = s.last
  from (
        select i.dish_id, count(*)::int as n, max(o.confirmed_at) as last
          from meal_order_items i
          join meal_orders o on o.id = i.order_id
         where o.status <> 'draft'
         group by i.dish_id
  ) s
 where d.id = s.dish_id;

