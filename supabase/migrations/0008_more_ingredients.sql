-- 0008 · 主食材补两项：动物内脏、其他海鲜
--
-- 需求是"新增菜品时主食材里选得到这两样"。其他海鲜在 0006 已经进来了，
-- 这里把它一起写成 on conflict do nothing，所以这个文件在新库和旧库上跑都落到同一个结果。
--
-- 注意「主食材」下拉是**不按分类过滤**的：DishForm.vue 直接 v-for 全部 ingredients，
-- 所以选 荤菜 时也会看到 蔬菜、豆腐。这是原设计（食材和分类是两个独立概念，见原则一），
-- 不是漏了过滤。真要做"选荤菜只给我看肉/水产/内脏"，得先决定那些边界菜怎么归类。
-- =============================================================================

insert into ingredients (name, kind) values
  ('动物内脏', '肉类'),
  ('其他海鲜', '水产')
on conflict (name) do nothing;

-- 校验：select name, kind from ingredients where name in ('动物内脏','其他海鲜');
-- 下拉按 id 排序，所以这两项会排在列表末尾。
